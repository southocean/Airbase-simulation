const DICTS: Record<Lang, Dict> = { en: EN, sv: SV };

export const LANGUAGES: { id: Lang; label: string; flag: string }[] = [
  { id: "en", label: "English", flag: "EN" },
  { id: "sv", label: "Svenska", flag: "SV" },
];

function interpolate(template: string, p?: Record<string, string | number>): string {
  if (!p) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) => (key in p ? String(p[key]) : `{${key}}`));
}

/** Translate a key with parameters. Falls back to English, then to the key. */
export function translate(lang: Lang, key: string, p?: Record<string, string | number>): string {
  const raw = DICTS[lang][key] ?? EN[key];
  if (raw === undefined) return key;
  return interpolate(raw, p);
}

/** Translate a structured Msg emitted by the simulation core. */
export function translateMsg(lang: Lang, m: Msg): string {
  const resolved = m.p
    ? Object.fromEntries(
        Object.entries(m.p).map(([k, v]) => [
          k,
          // A parameter may itself be a key (e.g. a nested reason or job label).
          typeof v === "string" && /^[a-z]+\.[A-Za-z0-9_]+$/.test(v) ? translate(lang, v) : v,
        ]),
      )
    : undefined;
  return translate(lang, m.k, resolved);
}
