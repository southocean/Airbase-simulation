/**
 * Localisation.
 *
 * English is the default. Swedish is offered because the domain vocabulary is
 * Swedish and the operators this is modelled on work in it — but nobody should
 * have to read Swedish to understand the simulation.
 *
 * Architectural point: the simulation core does NOT produce display strings. It
 * emits `Msg` values — a key plus parameters — and this module renders them. That
 * keeps `src/sim` free of presentation concerns and means a headless batch run
 * has no opinion about language at all.
 */

export type Lang = "en" | "sv";

/** A translatable message: key plus interpolation parameters. */
export interface Msg {
  k: string;
  p?: Record<string, string | number>;
}

export function msg(k: string, p?: Record<string, string | number>): Msg {
  return p ? { k, p } : { k };
}

